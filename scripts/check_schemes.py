#!/usr/bin/env python3
"""Keeps the apps Cabin Dash looks for and the Info.plist list in step.

iOS only answers "is this app installed?" for URL schemes listed under LSApplicationQueriesSchemes
(at most 50). The schemes live in CabinCore/Sources/CabinCore/Catalog.swift; the list lives in project.yml.

  python3 scripts/check_schemes.py           check, exit 1 if anything is wrong
  python3 scripts/check_schemes.py --write   rewrite the list in project.yml from Catalog.swift
"""
import pathlib
import plistlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "CabinCore/Sources/CabinCore/Catalog.swift"
PLACES = ROOT / "CabinCore/Sources/CabinCore/Places.swift"
PROJECT = ROOT / "project.yml"
INFO_PLIST = ROOT / "Config/Info.plist"  # generated by XcodeGen; also usable by hand-made Xcode projects
BEGIN, END = "# BEGIN SCHEMES", "# END SCHEMES"
LIMIT = 50


def catalog_entries():
    entries = []
    for number, line in enumerate(CATALOG.read_text().splitlines(), 1):
        text = line.strip()
        if not text.startswith('app("'):
            continue
        ident = re.match(r'app\("([^"]+)"', text).group(1)
        scheme = re.search(r'\bs:\s*"([^"]+)"', text)
        track = re.search(r'\bt:\s*(\d+)', text)
        entries.append({
            "line": number,
            "id": ident,
            "scheme": scheme.group(1) if scheme else None,
            "track": int(track.group(1)) if track else None,
        })
    return entries


def project_schemes():
    lines = PROJECT.read_text().splitlines()
    inside, found = False, []
    for line in lines:
        if BEGIN in line:
            inside = True
        elif END in line:
            inside = False
        elif inside and line.strip().startswith("- "):
            found.append(line.strip()[2:].strip())
    return found


def plist_schemes():
    if not INFO_PLIST.exists():
        return None
    with INFO_PLIST.open("rb") as f:
        return plistlib.load(f).get("LSApplicationQueriesSchemes", [])


def write_plist(schemes):
    if not INFO_PLIST.exists():
        return
    with INFO_PLIST.open("rb") as f:
        info = plistlib.load(f)
    info["LSApplicationQueriesSchemes"] = schemes
    with INFO_PLIST.open("wb") as f:
        plistlib.dump(info, f, sort_keys=True)


def write_schemes(schemes):
    lines = PROJECT.read_text().splitlines()
    out, skipping = [], False
    for line in lines:
        if BEGIN in line:
            indent = line[: len(line) - len(line.lstrip())]
            out.append(line)
            out.extend(f"{indent}- {s}" for s in schemes)
            skipping = True
        elif END in line:
            skipping = False
            out.append(line)
        elif not skipping:
            out.append(line)
    PROJECT.write_text("\n".join(out) + "\n")


def main():
    entries = catalog_entries()
    problems = []

    ids = [e["id"] for e in entries]
    for ident in sorted({i for i in ids if ids.count(i) > 1}):
        problems.append(f"duplicate app id: {ident}")
    tracks = [e["track"] for e in entries if e["track"]]
    for track in sorted({t for t in tracks if tracks.count(t) > 1}):
        problems.append(f"duplicate App Store id: {track}")

    wanted = []
    for e in entries:
        s = e["scheme"]
        if s and s not in wanted:
            wanted.append(s)
        if s and ("://" in s or ":" in s or "/" in s):
            problems.append(f"Catalog.swift line {e['line']}: scheme '{s}' must be the bare name, without '://'")

    block = re.search(r"var scheme: String\? \{(.*?)\n    \}", PLACES.read_text(), re.S)
    nav = re.findall(r'return "([^"]+)"', block.group(1)) if block else []
    if not nav:
        problems.append("Places.swift: could not find NavApp.scheme")
    for s in nav:
        if s not in wanted:
            problems.append(f"Places.swift: the maps app scheme '{s}' is missing from Catalog.swift")

    if len(wanted) > LIMIT:
        problems.append(f"{len(wanted)} schemes; iOS only honours {LIMIT} in LSApplicationQueriesSchemes")

    if "--write" in sys.argv:
        write_schemes(wanted)
        write_plist(wanted)
        print(f"Wrote {len(wanted)} schemes to project.yml and Config/Info.plist")
        have = wanted
    else:
        have = project_schemes()

    for s in wanted:
        if s not in have:
            problems.append(f"'{s}' is in Catalog.swift but not in project.yml (run with --write)")
    for s in have:
        if s not in wanted:
            problems.append(f"'{s}' is in project.yml but no catalog app uses it (run with --write)")

    plist = plist_schemes()
    if plist is not None and plist != wanted:
        problems.append("Config/Info.plist has a different scheme list (run with --write)")

    print(f"{len(entries)} catalog apps, {len(wanted)} schemes (limit {LIMIT})")
    if problems:
        print("\nProblems:")
        for p in problems:
            print(" -", p)
        return 1
    print("OK: Catalog.swift and project.yml agree.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
